DO $$
DECLARE
  course_id_type text;
  enrollment_course_id_type text;
  enrollment_course_id_attnum smallint;
  foreign_key record;
BEGIN
  SELECT format_type(attribute.atttypid, attribute.atttypmod)
  INTO course_id_type
  FROM pg_attribute AS attribute
  WHERE attribute.attrelid = 'public.courses'::regclass
    AND attribute.attname = 'id'
    AND NOT attribute.attisdropped;

  IF to_regclass('public.enrollments') IS NULL THEN
    EXECUTE format(
      'CREATE TABLE public.enrollments (
        course_id %s NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
        student_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
        PRIMARY KEY (course_id, student_id)
      )',
      course_id_type
    );
  ELSE
    SELECT format_type(attribute.atttypid, attribute.atttypmod)
    INTO enrollment_course_id_type
    FROM pg_attribute AS attribute
    WHERE attribute.attrelid = 'public.enrollments'::regclass
      AND attribute.attname = 'course_id'
      AND NOT attribute.attisdropped;

    IF enrollment_course_id_type IS NULL THEN
      RAISE EXCEPTION 'public.enrollments must contain a course_id column.';
    END IF;

    IF enrollment_course_id_type IS DISTINCT FROM course_id_type THEN
      SELECT attribute.attnum
      INTO enrollment_course_id_attnum
      FROM pg_attribute AS attribute
      WHERE attribute.attrelid = 'public.enrollments'::regclass
        AND attribute.attname = 'course_id'
        AND NOT attribute.attisdropped;

      FOR foreign_key IN
        SELECT constraint_row.conname
        FROM pg_constraint AS constraint_row
        WHERE constraint_row.conrelid = 'public.enrollments'::regclass
          AND constraint_row.contype = 'f'
          AND enrollment_course_id_attnum = ANY(constraint_row.conkey)
      LOOP
        EXECUTE format(
          'ALTER TABLE public.enrollments DROP CONSTRAINT %I',
          foreign_key.conname
        );
      END LOOP;

      EXECUTE format(
        'ALTER TABLE public.enrollments ALTER COLUMN course_id TYPE %s USING course_id::%s',
        course_id_type,
        course_id_type
      );
    END IF;
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint AS constraint_row
    WHERE constraint_row.conrelid = 'public.enrollments'::regclass
      AND constraint_row.confrelid = 'public.courses'::regclass
      AND constraint_row.contype = 'f'
      AND EXISTS (
        SELECT 1
        FROM unnest(constraint_row.conkey) AS key_column(attnum)
        JOIN pg_attribute AS attribute
          ON attribute.attrelid = constraint_row.conrelid
         AND attribute.attnum = key_column.attnum
        WHERE attribute.attname = 'course_id'
      )
  ) THEN
    ALTER TABLE public.enrollments
      ADD CONSTRAINT enrollments_course_id_fkey
      FOREIGN KEY (course_id)
      REFERENCES public.courses(id)
      ON DELETE CASCADE;
  END IF;
END;
$$;

