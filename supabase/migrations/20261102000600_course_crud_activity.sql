CREATE OR REPLACE FUNCTION public.admin_save_course(
  p_course_id text,
  p_title text,
  p_subject text,
  p_description text,
  p_grade_level text,
  p_teacher_id uuid,
  p_active boolean,
  p_student_ids uuid[]
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_course_id public.courses.id%TYPE;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Only administrators can manage courses.'
      USING ERRCODE = '42501';
  END IF;

  IF nullif(btrim(p_title), '') IS NULL
     OR nullif(btrim(p_subject), '') IS NULL
     OR nullif(btrim(p_grade_level), '') IS NULL
     OR p_teacher_id IS NULL
     OR coalesce(cardinality(p_student_ids), 0) = 0 THEN
    RAISE EXCEPTION 'Course name, subject, grade, teacher, and students are required.';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = p_teacher_id AND role = 'teacher'
  ) THEN
    RAISE EXCEPTION 'Selected teacher is not a teacher account.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM unnest(p_student_ids) AS selected(student_id)
    LEFT JOIN public.profiles AS profile ON profile.id = selected.student_id
    WHERE profile.id IS NULL OR profile.role <> 'student'
  ) THEN
    RAISE EXCEPTION 'All selected users must be student accounts.';
  END IF;

  IF p_course_id IS NULL THEN
    INSERT INTO public.courses (
      title, subject, description, grade_level, teacher_id, status
    )
    VALUES (
      btrim(p_title), btrim(p_subject), btrim(coalesce(p_description, '')),
      btrim(p_grade_level), p_teacher_id,
      CASE WHEN p_active THEN 'active' ELSE 'inactive' END
    )
    RETURNING id INTO v_course_id;
  ELSE
    UPDATE public.courses
    SET title = btrim(p_title),
        subject = btrim(p_subject),
        description = btrim(coalesce(p_description, '')),
        grade_level = btrim(p_grade_level),
        teacher_id = p_teacher_id,
        status = CASE WHEN p_active THEN 'active' ELSE 'inactive' END
    WHERE id::text = p_course_id
    RETURNING id INTO v_course_id;

    IF v_course_id IS NULL THEN
      RAISE EXCEPTION 'Course not found.';
    END IF;
  END IF;

  DELETE FROM public.enrollments
  WHERE public.enrollments.course_id::text = v_course_id::text
    AND NOT (
      student_id::text = ANY (
        ARRAY(SELECT selected_id::text FROM unnest(p_student_ids) AS selected_id)
      )
    );

  INSERT INTO public.enrollments (course_id, student_id)
  SELECT v_course_id, selected.student_id
  FROM (
    SELECT DISTINCT unnest(p_student_ids) AS student_id
  ) AS selected
  WHERE NOT EXISTS (
    SELECT 1
    FROM public.enrollments AS enrolled
    WHERE enrolled.course_id::text = v_course_id::text
      AND enrolled.student_id::text = selected.student_id::text
  );

  RETURN v_course_id::text;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_delete_course(p_course_id text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Only administrators can manage courses.'
      USING ERRCODE = '42501';
  END IF;

  DELETE FROM public.enrollments WHERE course_id::text = p_course_id;
  DELETE FROM public.courses WHERE id::text = p_course_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Course not found.';
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_save_course(
  text, text, text, text, text, uuid, boolean, uuid[]
