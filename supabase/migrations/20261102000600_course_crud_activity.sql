CREATE OR REPLACE FUNCTION public.log_table_activity()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  row_data jsonb;
  actor text;
  actor_type text;
  entity_key text;
  entity_title text;
BEGIN
  row_data := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
  entity_key := coalesce(
    row_data ->> 'id',
    row_data ->> 'id_user',
    row_data ->> 'course_id'
  );
  entity_title := coalesce(
    row_data ->> 'title',
    row_data ->> 'name',
    row_data ->> 'nama',
    row_data ->> 'nama_lengkap',
    row_data ->> 'judul',
    row_data ->> 'email',
    TG_ARGV[0]
  );

  SELECT p.full_name
       , p.role
  INTO actor, actor_type
  FROM public.profiles AS p
  WHERE p.id = auth.uid();

  INSERT INTO public.activity_logs (
    actor_id,
    actor_name,
    actor_role,
    action,
    entity,
    entity_id,
    entity_name
  )
  VALUES (
    auth.uid(),
    coalesce(actor, 'Admin'),
    coalesce(actor_type, 'admin'),
    lower(TG_OP),
    TG_ARGV[0],
    entity_key,
    entity_title
  );

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.log_table_activity() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.log_table_activity() TO authenticated;

CREATE OR REPLACE FUNCTION public.record_user_activity(
  p_action text,
  p_entity text,
  p_entity_name text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  actor_role text;
  actor_name text;
BEGIN
  SELECT profile.role, profile.full_name
  INTO actor_role, actor_name
  FROM public.profiles AS profile
  WHERE profile.id = auth.uid();

  IF auth.uid() IS NULL OR actor_role IS NULL THEN
    RAISE EXCEPTION 'Login diperlukan untuk mencatat aktivitas.'
      USING ERRCODE = '42501';
  END IF;

  IF (
    actor_role = 'teacher'
    AND p_action IN ('insert', 'update', 'delete')
    AND p_entity IN ('material', 'quiz')
  ) OR (
    actor_role = 'student'
    AND p_action IN ('complete', 'submit')
    AND p_entity IN ('material', 'quiz')
  ) THEN
    INSERT INTO public.activity_logs (
      actor_id, actor_name, actor_role, action, entity, entity_name
    )
    VALUES (
      auth.uid(),
      coalesce(actor_name, 'Pengguna'),
      actor_role,
      p_action,
      p_entity,
      coalesce(nullif(btrim(p_entity_name), ''), initcap(p_entity))
    );
    RETURN;
  END IF;

  RAISE EXCEPTION 'Aktivitas tidak diizinkan untuk role ini.'
    USING ERRCODE = '42501';
END;
$$;

REVOKE ALL ON FUNCTION public.record_user_activity(text, text, text)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.record_user_activity(text, text, text)
  TO authenticated;

